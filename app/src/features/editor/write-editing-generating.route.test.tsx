import { screen } from '@testing-library/react';
import { beforeEach, describe, expect, it } from 'vitest';

import { db } from '@/mocks/db';
import { useEditorStore } from '@/stores/editor-store';
import { renderRouterApp } from '@/test/router-test-utils';

// One test per file for routed studio tests that mount the manuscript chunk: see
// `manuscript-sheet-readonly.route.test.tsx`.
const LONG = { timeout: 10000 };

beforeEach(() => useEditorStore.setState({ view: 'write' }));

describe('Studio editor pane (routed) — the Write view while a run generates the section', () => {
  it('is the read-only view, with the notice, and never loads the editor', async () => {
    const node = db.outlineNodes.get('rl-sec-1-1')!;
    db.outlineNodes.set(node.id, { ...node, status: 'drafting' });
    renderRouterApp('/p/book-reinforcement-learning?node=rl-sec-1-1');
    expect(await screen.findByText(/being generated by a run/i, {}, LONG)).toBeInTheDocument();
    expect(await screen.findByText(/Because a finite MDP/, {}, LONG)).toBeInTheDocument();
    await new Promise((resolve) => setTimeout(resolve, 300));
    expect(document.querySelector('.md-editor')).toBeNull();
    expect(screen.queryByRole('textbox', { name: 'Section text' })).not.toBeInTheDocument();
  }, 30000);
});
