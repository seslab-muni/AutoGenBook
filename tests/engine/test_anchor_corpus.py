"""A small committed corpus for `resolve_quote`: one realistic section and the
quotes a reviewer model might hand back for it, including the tricky ones.
Each case names the exact span it must resolve to, or None (orphan). Precision
must be 100 %: a resolved quote that is not the expected span fails the test,
whatever the recall."""

from __future__ import annotations

import pytest

from engine.util.anchors import resolve_quote

LQ, RQ, AP, NBH, NBSP, ELL = "“", "”", "’", "‑", " ", "…"

SECTION = (
    "Stabilizer codes protect quantum information by restricting the state to the joint eigenspace of a set of commuting Pauli operators. "
    "The generators of S must pairwise commute, otherwise the group contains minus identity and the code space is empty.\n\n"
    "A **syndrome** is the vector of measurement outcomes of the generators. "
    "Its entries are +1 or -1, and a non-trivial syndrome signals that an error has occurred.\n\n"
    "Consider the following example. Let $n = 5$ and let S be generated by XZZXI and its cyclic shifts. "
    "This is the well-known five-qubit code, which corrects any single-qubit error.\n\n"
    "In summary, the code is not just small; it is optimal. The code is optimal for its parameters, and the code is also simple. "
    "Decoding uses a lookup table with 16 entries.\n\n"
    "The code is simple.\n\n"
    "The code corrects every single-qubit error [kb_report_ab12_page_3_1] and detects two errors. Compute $2*3*4 = 24$ first.\n"
)

CASES = [
    # (quote as a model writes it, expected span in SECTION or None)
    ("The generators of S must pairwise commute", "The generators of S must pairwise commute"),
    ("The generators of S must pairwise commute,", "The generators of S must pairwise commute,"),
    (f"{LQ}The generators of S must pairwise commute{RQ}", "The generators of S must pairwise commute"),
    ("The generators of S must pairwise  commute", "The generators of S must pairwise commute"),
    (f"{ELL}otherwise the group contains minus identity", "otherwise the group contains minus identity"),
    ("otherwise the group contains minus identity...", "otherwise the group contains minus identity"),
    ("The generators of S ... the code space is empty.", "The generators of S must pairwise commute, otherwise the group contains minus identity and the code space is empty."),
    ("A syndrome is the vector of measurement outcomes", "A **syndrome** is the vector of measurement outcomes"),
    ("syndrome", "**syndrome**"),
    (f"This is the well{NBH}known five-qubit code", "This is the well-known five-qubit code"),
    (f"corrects any single{NBSP}qubit error".replace(NBSP, "-"), "corrects any single-qubit error"),
    (f"Its entries are +1 or -1, and a non-trivial syndrome signals that an error has occurred.", "Its entries are +1 or -1, and a non-trivial syndrome signals that an error has occurred."),
    ("Decoding uses a lookup table with 16 entries", "Decoding uses a lookup table with 16 entries"),
    ("Let $n = 5$ and let S be generated by XZZXI", "Let $n = 5$ and let S be generated by XZZXI"),
    # ambiguous or too weak: orphan rather than a guess
    ("The code is simple.", "The code is simple."),   # unique with its capital T
    ("the code is", None),                         # several times
    ("is", None),                                  # a stray word
    ("5.", None),                                  # a digit with a period
    ("a", None),
    ('"a"', None),
    ("It ... a", None),
    ("Stabilizer ... empty", None),                # short segments around an ellipsis
    # not in the text at all
    ("Decoding uses a lookup table with 32 entries and a hash map", None),
    ("The syndrome is always +1 for every valid state of the code", None),
    ("Photosynthesis converts light energy into chemical energy", None),
    # small paraphrases of a long sentence: fuzzy may resolve them, never elsewhere
    ("Its entries are +1 or -1 and a nontrivial syndrome signals that an error occurred.", "Its entries are +1 or -1, and a non-trivial syndrome signals that an error has occurred."),
    # sub-word and tiny quotes: only with something to vouch for them
    ("x", None),
    ("5", None),
    ("ell", None),
    # a quote spanning a citation marker the reviewer never saw
    ("The code corrects every single-qubit error and detects two errors.", "The code corrects every single-qubit error [kb_report_ab12_page_3_1] and detects two errors."),
    # emphasis delimiters inside math and code are operators, not Markdown
    ("234 = 24 is the product", None),
    ("Compute 2*3*4 = 24 first.", "Compute $2*3*4 = 24$ first."),
]


@pytest.mark.parametrize("quote, expected", CASES)
def test_corpus_case_is_never_resolved_to_a_wrong_span(quote: str, expected: str | None) -> None:
    anchor = resolve_quote(SECTION, quote)
    if anchor["start"] is None:
        return  # an orphan is always acceptable for precision; recall is asserted below
    assert expected is not None, f"false positive: {SECTION[anchor['start']:anchor['end']]!r}"
    assert SECTION[anchor["start"]:anchor["end"]] == anchor["quote"]
    assert anchor["quote"] == expected


def test_corpus_precision_is_100_percent_and_recall_is_high() -> None:
    resolved = wrong = expected_total = hit = 0
    for quote, expected in CASES:
        anchor = resolve_quote(SECTION, quote)
        if expected is not None:
            expected_total += 1
        if anchor["start"] is None:
            continue
        resolved += 1
        if anchor["quote"] == expected:
            hit += 1
        else:
            wrong += 1
    assert wrong == 0
    assert hit / expected_total >= 0.9, (hit, expected_total)
